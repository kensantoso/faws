# --- adversarial: an empty-ish role value (key present, value empty) ---
[profile emptyrole-profile]
granted_sso_start_url  = https://scale-adversarial.awsapps.com/start
granted_sso_region     = us-east-1
granted_sso_account_id = 990000000040
granted_sso_role_name  =
