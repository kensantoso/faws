credential_process     = ${VENDOR} mfa-b/PowerUser

# --- adversarial: keys in unusual case, e.g. Granted_SSO_Role_Name. cutKV
# lowercases every key it reads, so these must behave identically to the
# lowercase form above (correct account/role display, correct filtering).
[profile casecheck-a/ReadOnly]
