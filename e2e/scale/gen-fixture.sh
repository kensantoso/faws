credential_process     = ${VENDOR} emptyrole-profile

# --- adversarial: role_arn + source_profile chains. Never vended by any test
# or sample: resolving them for real needs a genuine sts:AssumeRole network
# call, which this suite must never make. Visible to filtering only.
[profile chain-a]
role_arn       = arn:aws:iam::990000000050:role/ChainRoleA
source_profile = chain-base-a

[profile chain-b]
role_arn       = arn:aws:iam::990000000051:role/ChainRoleB
source_profile = chain-base-b

# --- adversarial: UPPERCASE secret keys whose secret VALUES contain common
# filter words. A correct faws must never match on aws_access_key_id /
# aws_secret_access_key regardless of the key's case in the file (cutKV
# lowercases keys; filter.SecretKeys excludes the lowercased names).
[profile shouty-scale-a]
AWS_ACCESS_KEY_ID     = AKIAFAKESCALE0000001
AWS_SECRET_ACCESS_KEY = uppercase-secret-scale-bait-readonly

[profile shouty-scale-b]
AWS_ACCESS_KEY_ID     = AKIAFAKESCALE0000002
AWS_SECRET_ACCESS_KEY = UPPERCASE-SECRET-SCALE-BAIT-ADMIN

# --- adversarial: mfa_serial profiles, for MFA counting/ordering at scale ---
[profile mfa-a/ReadOnly]
granted_sso_start_url  = https://scale-adversarial.awsapps.com/start
granted_sso_region     = us-east-1
granted_sso_account_id = 990000000060
granted_sso_role_name  = ReadOnly
