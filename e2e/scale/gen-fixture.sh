mfa_serial             = arn:aws:iam::990000000060:mfa/scale-a
credential_process     = ${VENDOR} mfa-a/ReadOnly

[profile mfa-b/PowerUser]
granted_sso_start_url  = https://scale-adversarial.awsapps.com/start
granted_sso_region     = us-east-1
granted_sso_account_id = 990000000061
