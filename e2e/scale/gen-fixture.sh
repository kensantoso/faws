Granted_SSO_Account_Id = 990000000071
Granted_SSO_Role_Name  = PowerUser
region                 = us-east-1
credential_process     = ${VENDOR} casecheck-b/PowerUser
EOF

# ---------------------------------------------------------------------------
# aws/credentials — 20 bare [name] sections: 4 deliberately collide with
# config profile names (config must win), 16 are new credsonly-NN profiles.
# Each collision carries a "note" marker value found nowhere in the config
# version, so a filter on that marker proves the credentials-file copy was
# dropped rather than merged or preferred.
# ---------------------------------------------------------------------------
cat >"$CREDS" <<'EOF'
# faws e2e/scale fixture — AWS shared credentials file, generated by
# gen-fixture.sh. DO NOT EDIT BY HAND; edit the generator and re-run it.
#
# 4 sections below collide with config profile names on purpose (config must
# win); each carries a "note = credswins-..." marker that must never surface
# through a filter, proving the collision was resolved in the config file's
# favor. The other 16 are new credsonly-NN profiles found nowhere in config.

[nimbus]
aws_access_key_id     = AKIAFAKECREDSNIMBUS1
aws_secret_access_key = fake-creds-nimbus-secret
note                   = credswins-nimbus-should-not-appear

[shouty-scale-a]
aws_access_key_id     = AKIAFAKECREDSSHOUTY1
aws_secret_access_key = fake-creds-shouty-secret
note                   = credswins-shouty-scale-a-should-not-appear

[mfa-a/ReadOnly]
aws_access_key_id     = AKIAFAKECREDSMFA0001
aws_secret_access_key = fake-creds-mfa-secret
note                   = credswins-mfa-a-readonly-should-not-appear

[org05-acct3/Admin]
aws_access_key_id     = AKIAFAKECREDSORG0001
aws_secret_access_key = fake-creds-org-secret
note                   = credswins-org05-acct3-admin-should-not-appear

EOF

n=0
while [ "$n" -le 15 ]; do
	nn=$(printf '%02d' "$n")
	cat >>"$CREDS" <<EOF
[credsonly-${nn}]
aws_access_key_id     = AKIAFAKECREDSONLY${nn}
aws_secret_access_key = fake-credsonly-${nn}-secret
note                   = scale-creds-only-${nn}

EOF
	n=$((n + 1))
done

echo "wrote $(grep -c '^\[profile ' "$CONFIG") config profiles to $CONFIG"
echo "wrote $(grep -c '^\[' "$CREDS") credentials sections to $CREDS"
